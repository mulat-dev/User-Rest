export const createTranslator = (language) => {
  const dictionary = translations[language] || translations.English;

  return (key, replacements = {}) => {
    let text = dictionary[key] || translations.English[key] || key;
    Object.entries(replacements).forEach(([token, value]) => {
      text = text.replace(`{${token}}`, value);
    });
    return text;
  };
};

export const getLocaleForLanguage = (language) => {
  if (language === "Amharic") {
    return "am-ET";
  }
  if (language === "Tigrigna") {
    return "ti-ET";
  }
  return "en-US";
};

export const translateCategory = (language, category) => {
  const t = createTranslator(language);
  const categoryMap = {
    Soup: "categorySoup",
    Salad: "categorySalad",
    Noodles: "categoryNoodles",
    Rice: "categoryRice",
    Sizzling: "categorySizzling",
    "Veggie Corner": "categoryVeggieCorner",
    Variety: "categoryVariety",
    Mojito: "categoryMojito",
    Smoothie: "categorySmoothie",
    Extras: "categoryExtras",
  };
  return t(categoryMap[category] || category);
};

export const translateTag = (language, tag) => {
  const t = createTranslator(language);
  const tagMap = {
    Popular: "tagPopular",
    Signature: "tagSignature",
  };
  return t(tagMap[tag] || tag);
};
